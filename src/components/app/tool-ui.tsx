/** Score → width + tone. 10 is always "better" in every coach output. */
export function scoreTone(score: number): { bar: string; text: string } {
  if (score >= 8) return { bar: "bg-accent-500", text: "text-accent-500" };
  if (score >= 6) return { bar: "bg-brand-500", text: "text-brand-600 dark:text-brand-300" };
  if (score >= 4) return { bar: "bg-warn", text: "text-warn" };
  return { bar: "bg-risk", text: "text-risk" };
}

export function ScoreBar({
  label,
  score,
  detail,
  meta,
}: {
  label: string;
  score: number;
  detail?: string;
  meta?: string;
}) {
  const tone = scoreTone(score);
  return (
    <li className="rounded-md border border-line bg-surface p-3">
      <div className="flex items-baseline justify-between gap-3">
        <p className="text-[13px] font-medium">{label}</p>
        <p className="flex shrink-0 items-baseline gap-1.5">
          <span className={"font-mono text-sm font-semibold tabular-nums " + tone.text}>{score}</span>
          <span className="font-mono text-[10px] text-fg-faint">/10</span>
        </p>
      </div>
      <div className="mt-2 h-1.5 w-full overflow-hidden rounded-full bg-sunken">
        <div className={"h-full rounded-full " + tone.bar} style={{ width: `${score * 10}%` }} />
      </div>
      {detail ? <p className="mt-2 text-[12px] leading-relaxed text-fg-muted">{detail}</p> : null}
      {meta ? (
        <p className="mt-1.5 font-mono text-[10px] tracking-[0.12em] text-fg-faint uppercase">{meta}</p>
      ) : null}
    </li>
  );
}

export function ScoreDial({ score, grade }: { score: number; grade: string | null }) {
  const tone = scoreTone(Math.round(score / 10));
  return (
    <div className="flex items-center gap-4">
      <div className="text-right">
        <p className="font-mono text-4xl leading-none font-semibold tabular-nums">
          {score}
          <span className="text-base text-fg-faint">/100</span>
        </p>
        <p className="mt-1 font-mono text-[10px] tracking-[0.16em] text-fg-faint uppercase">
          Business opportunity score
        </p>
      </div>
      {grade ? (
        <span className={"badge " + tone.text}>
          <span className={"h-1.5 w-1.5 rounded-full " + tone.bar} aria-hidden />
          {grade}
        </span>
      ) : null}
    </div>
  );
}

export type ExperimentStatusUi = "proposed" | "running" | "done" | "dropped";

export function StatusBadge({ status }: { status: ExperimentStatusUi }) {
  const map: Record<ExperimentStatusUi, { label: string; dot: string; text: string }> = {
    proposed: { label: "Proposed", dot: "bg-fg-faint", text: "text-fg-muted" },
    running: { label: "Running", dot: "bg-warn", text: "text-warn" },
    done: { label: "Done", dot: "bg-accent-500", text: "text-accent-500" },
    dropped: { label: "Dropped", dot: "bg-risk", text: "text-risk" },
  };
  const tone = map[status];
  return (
    <span className={"badge " + tone.text}>
      <span className={"h-1.5 w-1.5 rounded-full " + tone.dot} aria-hidden />
      {tone.label}
    </span>
  );
}

/** Labeled list ("KNOWN", "ASSUMED", "UNKNOWN") with a count and tone. */
export function FactList({
  title,
  hint,
  items,
  tone = "muted",
  emptyText,
}: {
  title: string;
  hint?: string;
  items: string[];
  tone?: "accent" | "brand" | "risk" | "muted";
  emptyText?: string;
}) {
  const dot =
    tone === "accent" ? "bg-accent-500" : tone === "brand" ? "bg-brand-500" : tone === "risk" ? "bg-risk" : "bg-fg-faint";
  return (
    <div className="rounded-md border border-line bg-surface p-3.5">
      <div className="flex items-center justify-between gap-2">
        <p className="flex items-center gap-2 font-mono text-[10px] tracking-[0.16em] text-fg-faint uppercase">
          <span className={"h-1.5 w-1.5 rounded-full " + dot} aria-hidden />
          {title}
        </p>
        <span className="font-mono text-[11px] tabular-nums text-fg-faint">{items.length}</span>
      </div>
      {hint ? <p className="mt-1.5 text-[11px] text-fg-faint">{hint}</p> : null}
      <ul className="mt-2.5 space-y-2">
        {items.length === 0 ? (
          <li className="text-[12px] text-fg-faint">{emptyText ?? "Nothing recorded yet."}</li>
        ) : (
          items.map((item, index) => (
            <li key={`${title}-${index}`} className="flex items-start gap-2 text-[12px] leading-relaxed text-fg-muted">
              <span className={"mt-1.5 h-1 w-1 shrink-0 rounded-full " + dot} aria-hidden />
              <span>{item}</span>
            </li>
          ))
        )}
      </ul>
    </div>
  );
}

/** Form field wrapper: `<label>` + optional hint, per DESIGN-SPEC §6. */
